import os

import numpy as np

from . import config, stats

PROBLEM_ORDER = ["TFIM", "QAOA", "VQC"]
NOISE_TXT = {"coherent": "coherent", "bitflip": "bit flip"}


def _tex_num(x, digits=2):
    """1.00, 0.31, 4.7\\times10^{3}"""
    if x < 100:
        return f"{x:.{digits}f}"
    e = int(np.floor(np.log10(x)))
    return f"{x / 10 ** e:.1f}\\times10^{{{e}}}"


def _eps_range(values):
    """Two significant digits, e.g. 0.011--0.30 (text-mode dash)."""
    lo, hi = "%#.2g" % min(values), "%#.2g" % max(values)
    return lo if lo == hi else f"{lo}--{hi}"


def continuation_rows(res, flat):
    """One row per curve of Figs. 2-4 (HVA last)."""
    rows = []
    for g in PROBLEM_ORDER:
        for kind in ("coherent", "bitflip"):
            r = res[g]
            recs, nom = r["records"][kind], r["nominal"][kind]
            lost = [x for x in recs if x.get("eps_reached") is not None]
            curve = [c for c in stats.curve(r, kind) if c["eps"] <= 1.01e-2]
            acc = [x for x in recs if x["ok"] and x["d"] > 0]
            rows.append(dict(
                problem=g, noise=kind, p=r["info"]["n_params"],
                dim=sorted(set(x["n_flat"] for x in nom if x["ok"])),
                runs=sum(x["ok"] for x in nom), lost=len(lost),
                lost_eps=[x["eps_reached"] for x in lost],
                lost_lmin=[x["lmin_reached"] / next(y["lmin"] for y in nom if y["seed"] == x["seed"])
                           for x in lost],
                slope=stats.loglog_slope([c["eps"] for c in curve], [c["gmean"] for c in curve]),
                ratio=float(np.median([x["dist_to_start"] / x["d"] for x in acc])),
                min_accepted=min(r["counts"][kind])))
    if flat is not None:
        curve = [c for c in stats.per_draw_curve(flat["eps"], flat["per_draw_dist"])
                 if c["eps"] <= 1.01e-2]
        rows.append(dict(problem="HVA", noise="coherent", p=3, dim=[0],
                         runs=len(flat["per_draw_dist"]), lost=0, lost_eps=[], lost_lmin=[],
                         slope=stats.loglog_slope([c["eps"] for c in curve], [c["gmean"] for c in curve]),
                         ratio=1.0, min_accepted=len(flat["per_draw_dist"])))
    return rows


def table_continuation(rows):
    body = []
    for r in rows:
        lost = f"{r['lost']}" + (f" ({_eps_range(r['lost_eps'])})" if r["lost"] else "")
        body.append(f"{r['problem']} & {NOISE_TXT[r['noise']]} & {r['runs']} & {lost} & "
                    f"${_tex_num(r['slope'])}$ & ${_tex_num(r['ratio'])}$ \\\\")
    return "\n".join([
        "% Table I: continuation runs behind Figs. 2-4 (generated by robustvqe/tables.py)",
        "\\begin{table}[t]",
        "\\caption{\\label{tab:runs}Continuation runs behind Figs.~\\ref{coherentplot}--\\ref{flatplot}. "
        "Runs: initializations, each with a certified noise-free minimizer $\\theta^*$ and its own "
        "error draw (HVA: error draws at its single minimizer). Lost: runs whose branch of perturbed "
        "minimizers could not be followed up to $\\epsilon=10^{-1/2}$, with the values of $\\epsilon$ "
        "at which this happened. Slope: least-squares slope of the geometric mean of "
        "$\\mathrm{dist}(\\tilde\\theta^*_\\epsilon,\\Theta^*)$ against $\\epsilon$ in log-log scale "
        "for $\\epsilon\\leq10^{-2}$. $r$: median of "
        "$\\|\\tilde\\theta^*_\\epsilon-\\theta^*\\|/\\mathrm{dist}(\\tilde\\theta^*_\\epsilon,\\Theta^*)$ "
        "over all accepted points. $r=1$ means that the perturbed minimizer stays next to $\\theta^*$, "
        "while $r\\gg1$ means that it moved along $\\Theta^*$. For the $SU(N)$ ansatz, $\\Theta^*$ "
        f"is a manifold of dimension {rows[0]['dim'][0]}; the minima of QAOA and of the HVA are "
        "isolated, so that $r=1$ there.}",
        "\\begin{ruledtabular}",
        "\\begin{tabular}{llrlll}",
        "Problem & Noise & Runs & Lost & Slope & $r$ \\\\",
        "\\hline",
        *body,
        "\\end{tabular}",
        "\\end{ruledtabular}",
        "\\end{table}",
    ])


def convergence_rows(conv):
    rows = []
    for (g, kind), r in sorted(conv.items(), key=lambda kv: (kv[0][0] != "TFIM", kv[0][1] != "none",
                                                            kv[0][1] != "coherent")):
        recs = r["records"]
        n = r["runs"] * len(r["eps"])
        row = dict(problem=g, noise=kind, eps=r["eps"], runs=r["runs"], K=r["K"],
                   increases=sum(x["increases"] for x in recs),
                   gd_within=sum(x["f_gd"] - x["f_ref"] <= r["tol_e"] for x in recs),
                   certified=sum(x["cert_ok"] for x in recs), total=n,
                   distinct=[len(set(np.round([x["f"] for x in recs if x["eps"] == e], 8)))
                             for e in r["eps"]])
        if "global" in recs[0]:
            row.update(glob=sum(x["global"] for x in recs),
                       max_gap=max(abs(x["gap"]) for x in recs))
        if "dist" in recs[0] and kind != "none":
            c = [stats.geo_stats([x["dist"] for x in recs if x["eps"] == e])["gmean"] / e
                 for e in r["eps"]]
            cg = [stats.geo_stats([x["dist_gd"] for x in recs if x["eps"] == e])["gmean"] / e
                  for e in r["eps"]]
            row.update(c_lim=(min(c), max(c)), c_gd=(min(cg), max(cg)))
        rows.append(row)
    return rows


def table_convergence(rows):
    body = []
    for r in rows:
        noise = {"none": "none", "coherent": "coherent", "bitflip": "bit flip"}[r["noise"]]
        eps = "$0$" if r["noise"] == "none" else "$10^{-3}$--$10^{-1/2}$"
        if "glob" in r:
            gd = f"{r['gd_within']}/{r['total']}"
            lim = f"{r['glob']}/{r['total']}"
            c = (f"${r['c_lim'][0]:.2f}$--${r['c_lim'][1]:.2f}$" if "c_lim" in r else "--")
        else:
            gd, lim, c = "--", f"{min(r['distinct'])} distinct", "--"
        body.append(f"{r['problem']} & {noise} & {eps} & {gd} & {lim} & {c} \\\\")
    K = rows[0]["K"]
    return "\n".join([
        "% Table II: gradient descent on the perturbed cost (generated by robustvqe/tables.py)",
        "\\begin{table}[t]",
        "\\caption{\\label{tab:convergence}Gradient descent~(\\ref{gradientdescent}) on the perturbed cost from "
        f"{rows[0]['runs']} initial points per $\\epsilon$. GD: runs with "
        f"$\\tilde\\ell(\\theta^K)-\\tilde\\ell^*\\leq10^{{-9}}$ after $K={K}$ iterations. "
        "Limit: runs whose limit $\\theta^\\infty$ (descent continued with L-BFGS) is a certified "
        "global minimizer of $\\tilde\\ell$; for QAOA, whose minimum value is not known, the number "
        "of distinct local minima reached at each $\\epsilon$. Distance: "
        "$\\mathrm{dist}(\\theta^\\infty,\\Theta^*)/\\epsilon$ (geometric mean over the runs; range "
        "over $\\epsilon$).}",
        "\\begin{ruledtabular}",
        "\\begin{tabular}{llllll}",
        "Problem & Noise & $\\epsilon$ & GD & Limit & Distance \\\\",
        "\\hline",
        *body,
        "\\end{tabular}",
        "\\end{ruledtabular}",
        "\\end{table}",
    ])


def report(res, conv, flat, crows, vrows):
    """Every number quoted in Sec. VII, recomputed."""
    L = ["Numbers quoted in Sec. VII, recomputed from the stored results", ""]
    L.append("VII.A  Optimal parameter distance (Figs. 2-4, Table I)")
    for g in PROBLEM_ORDER:
        L.append(f"  {g}: p = {res[g]['info']['n_params']} parameters, "
                 f"E0 = {res[g]['problem']['e0']:.6f}, degeneracy {res[g]['problem']['degeneracy']}")
    for r in crows:
        line = (f"  {r['problem']:4s} {r['noise']:8s}: runs {r['runs']}, accepted minimisers per eps "
                f">= {r['min_accepted']}, slope {r['slope']:.3f}, median r {r['ratio']:.3g}")
        if r["lost"]:
            line += (f"; {r['lost']} of {r['runs']} branches lost at eps in "
                     f"[{min(r['lost_eps']):.3f}, {max(r['lost_eps']):.3f}] (lambda_min at the last "
                     f"followed point / at theta*: {min(r['lost_lmin']):.2f}-{max(r['lost_lmin']):.2f}, "
                     f"median {np.median(r['lost_lmin']):.2f})")
        L.append(line)
    if flat is not None:
        L.append(f"  HVA flat point: h_c = {flat['h_c']:.10f}, x* = {np.round(flat['x_star'], 6).tolist()}, "
                 f"quartic coefficient a = {flat['a']:.5f} (> 0), curvature along the tilt "
                 f"{flat['mu']:.1e}, (gamma, beta) block eigenvalues "
                 f"{np.round(flat['even_eigenvalues'], 3).tolist()} (> 0: isolated minimum)")
        L.append(f"  HVA: cost at x* {flat['value']:.10f}, best of {flat['settings']['random_starts']} "
                 f"random starts {flat['best_random_start']:.10f}; slope {flat['slope']:.3f} "
                 f"(per draw {min(flat['slopes_per_draw']):.3f}-{max(flat['slopes_per_draw']):.3f})")
    if config.SAME_FIELD_NAME in res:
        r = res[config.SAME_FIELD_NAME]
        curve = stats.curve(r, "coherent")
        L.append(f"  SU(N) at h = {r['spec']['problem_kwargs']['h']:.10f} (Fig. 4): slope "
                 f"{stats.loglog_slope([c['eps'] for c in curve if c['eps'] <= 1.01e-2], [c['gmean'] for c in curve if c['eps'] <= 1.01e-2]):.3f}, "
                 f"dist/eps at the smallest eps {curve[0]['gmean'] / curve[0]['eps']:.3f}")
    L.append("")
    L.append("VII.B  Asymptotic convergence (Fig. 5, Table II)")
    for r in vrows:
        line = (f"  {r['problem']:4s} {r['noise']:8s}: {r['runs']} runs per eps, K = {r['K']}, cost "
                f"increases {r['increases']}, certified limits {r['certified']}/{r['total']}")
        if "glob" in r:
            line += (f", within 1e-9 after GD {r['gd_within']}/{r['total']}, global limits "
                     f"{r['glob']}/{r['total']}, max |l~(theta^infty) - l~*| {r['max_gap']:.1e}")
        else:
            line += f", distinct local minima per eps {r['distinct']}"
        if "c_lim" in r:
            line += (f", dist(theta^K, Theta*)/eps {r['c_gd'][0]:.2f}-{r['c_gd'][1]:.2f}, "
                     f"dist(theta^infty, Theta*)/eps {r['c_lim'][0]:.2f}-{r['c_lim'][1]:.2f}")
        L.append(line)
    L.append("")
    L.append("VII.C  Special cases (Figs. 6-7)")
    q = res["QAOA"]
    for kind in ("control", "control_global"):
        acc = [x for x in q["records"][kind] if x["ok"]]
        L.append(f"  QAOA {kind}: accepted {len(acc)}/{len(q['records'][kind])}, max |theta~* - "
                 f"theta*/(1+eta)| = {max(x['closed_form_err'] for x in acc):.1e}, "
                 f"|theta~* - theta*| / (||eta||_inf |theta~*|) in "
                 f"[{min(x['d'] / x['bound'] for x in acc):.3f}, {max(x['d'] / x['bound'] for x in acc):.3f}]")
    acc = [x for x in res["TFIM"]["records"]["depolarizing"] if x["ok"]]
    L.append(f"  TFIM depolarizing: accepted {len(acc)}/{len(res['TFIM']['records']['depolarizing'])}, "
             f"largest distance {max(x['d'] for x in acc):.1e}")
    return "\n".join(L)


def make_all(results_dir, outdir):
    os.makedirs(outdir, exist_ok=True)
    res = stats.load(results_dir)
    conv = stats.load_convergence(results_dir)
    flat = stats.load_flat(results_dir)
    crows, vrows = continuation_rows(res, flat), convergence_rows(conv)
    for name, text in (("table_runs.tex", table_continuation(crows)),
                       ("table_convergence.tex", table_convergence(vrows)),
                       ("paper_numbers.txt", report(res, conv, flat, crows, vrows))):
        with open(os.path.join(outdir, name), "w") as fh:
            fh.write(text + "\n")
        print(f"wrote {outdir}/{name}")
    return crows, vrows
